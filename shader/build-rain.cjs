function packed(name,values,width,height){
 const words=[];
 for(let i=0;i<values.length;i+=8){let w=0;for(let j=0;j<8;j++)w|=(Math.round(Math.max(0,Math.min(1,values[i+j]||0))*15)&15)<<(j*4);words.push('0x'+(w>>>0).toString(16)+'u');}
 return `const uint ${name}_DATA[${words.length}]=uint[${words.length}](\n${words.join(',')}\n);\nfloat ${name}Raw(ivec2 p){if(any(lessThan(p,ivec2(0)))||any(greaterThanEqual(p,ivec2(${width},${height}))))return 0.0;int i=p.y*${width}+p.x;return float((${name}_DATA[i/8]>>uint((i%8)*4))&15u)/15.0;}\nfloat ${name}(vec2 p){p-=.5;ivec2 q=ivec2(floor(p));vec2 f=fract(p);return mix(mix(${name}Raw(q),${name}Raw(q+ivec2(1,0)),f.x),mix(${name}Raw(q+ivec2(0,1)),${name}Raw(q+ivec2(1,1)),f.x),f.y);}\n`;
}
function bucket(name,items,size,origin,width,encode){
 const sorted=[...items].sort((a,b)=>a.x-b.x),offsets=[];
 for(let k=0;k<=Math.ceil(width/size);k++){let i=sorted.findIndex(d=>d.x>=origin+k*size);offsets.push(i<0?sorted.length:i);}
 return `const int ${name}Offsets[${offsets.length}]=int[${offsets.length}](${offsets.join(',')});\nconst vec4 ${name}[${sorted.length}]=vec4[${sorted.length}](${sorted.map(encode).join(',')});\n`;
}
